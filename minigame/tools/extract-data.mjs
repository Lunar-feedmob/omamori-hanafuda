// Pulls the game's data tables out of the web build (index.html) so the mini game and the web page never drift apart.
// Usage: node minigame/tools/extract-data.mjs   (writes minigame/src/core/data.js)
import fs from 'node:fs';
import vm from 'node:vm';
const root = new URL('../../', import.meta.url).pathname;
const html = fs.readFileSync(root + 'index.html', 'utf8');
const slice = (from, to) => { const a = html.indexOf(from), b = html.indexOf(to, a); if (a < 0 || b < 0) throw new Error('marker not found: ' + from); return html.slice(a, b); };
const code = [
  slice('const MONTHS = [', 'const SKINS = {'),
  slice('const SEASONS = [', '// 庭外:'),
  slice('const VARIANTS = [', 'const MODES = {'),
  slice('const OM_TIERS = [', 'const omTier ='),
  slice('const WIN_TITLE = {', 'const levelFor =')
].join('\n') + '\n;({MONTHS, PLANT_NAMES, MOTIFS, YAKU, SEALS, SEASONS, KANJI, LEVELS, VARIANTS, OM_TIERS, WIN_TITLE, LOSE_TITLE})';
const d = vm.runInNewContext(code.replace(/^const BY_ID = .*$/m, ''), {});
const out = `// Generated by tools/extract-data.mjs from index.html — do not edit by hand.\n` +
  Object.entries(d).map(([k, v]) => `const ${k} = ${JSON.stringify(v)};`).join('\n') +
  `\nconst BY_ID = {}; MOTIFS.forEach(m => { BY_ID[m.id] = m; });\n` +
  `module.exports = {${Object.keys(d).join(', ')}, BY_ID};\n`;
fs.writeFileSync(root + 'minigame/src/core/data.js', out);
console.log('data.js', out.length, 'bytes;', d.MOTIFS.length, 'cards,', d.LEVELS.length, 'levels');
